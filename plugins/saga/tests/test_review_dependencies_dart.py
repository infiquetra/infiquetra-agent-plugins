@pytest.mark.skipif(
    os.environ.get("SAGA_TEST_LIVE_DART") != "1" or shutil.which("dart") is None,
    reason="opt-in (SAGA_TEST_LIVE_DART=1): needs the Dart SDK and the network",
)
def test_live_pub_fetches_a_lock_twice_identically(tmp_path: Path) -> None:
    repo = _live_repo(tmp_path)

    def runner(argv: list[str], *, cwd: Path, env: dict[str, str], timeout: int, shell: bool,
               umask: int | None = None) -> Any:
        proc = subprocess.run(argv, cwd=cwd, env=env, capture_output=True, text=True,
                              timeout=timeout, check=False)
        return _Result(proc.returncode, proc.stdout, proc.stderr)

    def export(dest: Path) -> bool:
        archive = subprocess.run(["git", "archive", "HEAD"], cwd=repo, check=True,
                                 capture_output=True).stdout
        subprocess.run(["tar", "-x", "-C", str(dest)], input=archive, check=True)
        return True

    packets = []
    for attempt in (1, 2):
        packet = tmp_path / f"packet-{attempt}"
        packet.mkdir()
        record = D.fetch(runner, repo, "HEAD", packet, export)
        packets.append((record, _contents(packet)))
    assert packets[0] == packets[1]
    entry = packets[0][0]["dart"]
    assert entry["state"] == "installed", entry
    assert "test" in {item["name"] for item in entry["packages"]}
    assert not any(str(tmp_path).encode() in value
                   for value in packets[0][1].values() if isinstance(value, bytes))


def _live_repo(tmp_path: Path) -> Path:
    """A from-scratch Dart package with one failing test, locked by the real pub."""
    repo = tmp_path / "repo"
    (repo / "lib").mkdir(parents=True)
    (repo / "test").mkdir()
    (repo / "pubspec.yaml").write_text(
        "name: tiny\nenvironment:\n  sdk: ^3.0.0\ndev_dependencies:\n  test: ^1.25.0\n", "utf-8")
    (repo / "lib" / "tiny.dart").write_text("int two() => 2;\n", "utf-8")
    (repo / "test" / "tiny_test.dart").write_text(
        "import 'package:test/test.dart';\nimport 'package:tiny/tiny.dart';\n\n"
        "void main() {\n  test('two is three', () {\n"
        "    expect(two(), 3, reason: 'two returned ${two()}');\n  });\n}\n", "utf-8")
    env = {**os.environ, "PUB_CACHE": str(tmp_path / "lock-cache"),
           "DASH__SUPPRESS_ANALYTICS": "true"}
    subprocess.run(["dart", "pub", "get"], cwd=repo, env=env, check=True, capture_output=True,
                   timeout=300)
    shutil.rmtree(repo / ".dart_tool")
    for args in (["init", "-q", "-b", "main"], ["config", "user.email", "t@example.com"],
                 ["config", "user.name", "t"], ["add", "-A"], ["commit", "-qm", "head"]):
        subprocess.run(["git", *args], cwd=repo, check=True)
    return repo
