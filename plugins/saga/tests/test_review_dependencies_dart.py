    ({"pubspec.yaml": PUBSPEC, "pubspec.lock": _lock(
        "  evil:\n    dependency: \"direct main\"\n    description:\n      path: \"/etc\"\n"
        "      relative: false\n    source: path\n    version: \"1.0.0\"\n")}, (),
     "unsupported-source"),
