def _export_with_link(tree: dict[str, str], link: str, target: Path) -> Any:
    def export(dest: Path) -> bool:
        _export_from(tree)(dest)
        (dest / link).parent.mkdir(parents=True, exist_ok=True)
        (dest / link).symlink_to(target)
        return True

    return export


