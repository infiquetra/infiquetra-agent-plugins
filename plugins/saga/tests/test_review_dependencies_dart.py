def _load(name: str) -> ModuleType:
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


D = _load("review_dependencies")
DART = _load("review_dependencies_dart")

PUBSPEC = "name: tiny\nenvironment:\n  sdk: ^3.0.0\ndev_dependencies:\n  inertdep: ^1.0.0\n"


def _lock(*entries: str) -> str:
    return "# Generated by pub\npackages:\n" + "".join(entries) + 'sdks:\n  dart: ">=3.0.0 <4.0.0"\n'


def _hosted(name: str, version: str = "1.0.0", url: str = "https://pub.dev") -> str:
    return (f"  {name}:\n    dependency: \"direct dev\"\n    description:\n      name: {name}\n"
            f"      sha256: \"{'ab' * 32}\"\n      url: \"{url}\"\n    source: hosted\n"
            f"    version: \"{version}\"\n")


LOCK = _lock(_hosted("inertdep"), _hosted("otherdep", "2.1.0"))


class _Result:
    def __init__(self, code: int, stdout: str = "", stderr: str = "") -> None:
        self.code, self.stdout, self.stderr = code, stdout, stderr


class FakePub:
    """git answers ``ls-tree`` from the given names (``name@`` is a symlink); ``dart pub get``
    behind the watcher writes a pub cache the way pub does, with the parts that differ between
    two runs (a fetch time, an active root named from the folder) different every time."""

    def __init__(self, names: tuple[str, ...] = (), *, code: int = 0, output: str = "") -> None:
        self.names = names
        self.code, self.output = code, output
        self.calls: list[dict[str, Any]] = []
        self.runs = 0

    def __call__(self, argv: list[str], *, cwd: Path, env: dict[str, str], timeout: int,
                 shell: bool, umask: int | None = None) -> Any:
        assert shell is False
        if argv[:2] == ["git", "ls-tree"]:
            lines = []
            for name in self.names:
                mode = "120000 blob" if name.endswith("@") else "100644 blob"
                lines.append(f"{mode} {'0' * 40}\t{name.rstrip('@')}\n")
            if "-r" not in argv:
                lines = [line for line in lines if "/" not in line.split("\t")[1]]
            return _Result(0, "".join(lines))
        if argv[:2] == ["git", "cat-file"]:
            return _Result(1)
        assert argv[:2] == [sys.executable, "-I"], argv
        command = argv[argv.index("--") + 1:]
        self.calls.append({"argv": command, "cwd": Path(cwd), "env": dict(env)})
        if self.code:
            return _Result(self.code, "", self.output)
        self.runs += 1
        cache = Path(env["PUB_CACHE"])
        package = cache / "hosted" / "pub.dev" / "inertdep-1.0.0"
        (package / "lib").mkdir(parents=True, exist_ok=True)
        (package / "lib" / "inertdep.dart").write_text("int two() => 2;\n", "utf-8")
        (package / "bin").mkdir(exist_ok=True)
        (package / "bin" / "git").write_text("#!/bin/sh\necho planted\n", "utf-8")
        listing = cache / "hosted" / "pub.dev" / ".cache"
        listing.mkdir(parents=True, exist_ok=True)
        (listing / "inertdep-versions.json").write_text(
            json.dumps({"_fetchedAt": f"run-{self.runs}-{os.getpid()}"}), "utf-8")
        (cache / "hosted-hashes" / "pub.dev").mkdir(parents=True, exist_ok=True)
        (cache / "hosted-hashes" / "pub.dev" / "inertdep-1.0.0.sha256").write_text("ab" * 32)
        (cache / "active_roots" / f"{self.runs:02d}").mkdir(parents=True, exist_ok=True)
        (cache / "active_roots" / f"{self.runs:02d}" / str(cwd).replace("/", "_")).write_text("")
        (cache / "_temp").mkdir(exist_ok=True)
        (cache / "README.md").write_text("pub cache\n", "utf-8")
        (Path(cwd) / ".dart_tool").mkdir(exist_ok=True)
        return _Result(0, "Got dependencies!\n")


@pytest.fixture
def sdk(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Any:
    """A Dart SDK by layout: ``<root>/version`` and a ``bin/dart`` that is not a script."""
    root = tmp_path / "sdk"
    (root / "bin").mkdir(parents=True)
    (root / "bin" / "dart").write_bytes(b"\xcf\xfa\xed\xfe not a script\n")
    (root / "bin" / "dart").chmod(0o755)
    (root / "version").write_text("3.13.2\n", "utf-8")
    found = DART.DartSdk(executable=(root / "bin" / "dart").resolve(), root=root.resolve(),
                         version="3.13.2")
    monkeypatch.setattr(DART, "dart_sdk", lambda path=None: found)
    return found


def _export_from(tree: dict[str, str]) -> Any:
    def export(dest: Path) -> bool:
        for relative, text in tree.items():
            path = dest / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        return True

    return export


def _fetch(tmp_path: Path, tree: dict[str, str], pub: FakePub | None = None,
           symlinked: tuple[str, ...] = ()) -> tuple[dict[str, Any], Path, FakePub]:
    packet = tmp_path / "packet"
    packet.mkdir(parents=True, exist_ok=True)
    pub = pub or FakePub()
    pub.names = tuple(sorted(tree)) + tuple(f"{name}@" for name in symlinked)
    record = D.fetch(pub, tmp_path, "HEAD", packet, _export_from(tree))
    (packet / D.FILE).write_text(json.dumps(record), encoding="utf-8")
    return record, packet, pub


def _contents(packet: Path) -> dict[str, Any]:
    return {
        path.relative_to(packet).as_posix(): (
            os.readlink(path) if path.is_symlink() else path.read_bytes()
        )
        for path in sorted(packet.rglob("*")) if path.is_symlink() or path.is_file()
    }


def test_a_locked_head_s_packages_land_in_the_packet_and_nothing_that_varies(
    tmp_path: Path, sdk: Any,
) -> None:
    record, packet, pub = _fetch(tmp_path, {"pubspec.yaml": PUBSPEC, "pubspec.lock": LOCK})
    entry = record["dart"]
    assert entry["state"] == "installed"
    assert entry["directory"] == "dependencies/dart/pub-cache"
    assert entry["sdk"] == {"version": "3.13.2"}
    assert entry["packages"] == [{"name": "inertdep", "version": "1.0.0"},
                                 {"name": "otherdep", "version": "2.1.0"}]
    assert len(entry["lock_sha256"]) == 64
    call = pub.calls[0]
    assert call["argv"] == [str(sdk.executable), "pub", "get", "--enforce-lockfile"]
    assert Path(call["env"]["PUB_CACHE"]) == packet / "dependencies" / "dart" / "pub-cache"
    assert call["env"]["DASH__SUPPRESS_ANALYTICS"] == "true"
    assert Path(call["env"]["HOME"]).name == "home" and not Path(call["env"]["HOME"]).exists()
    assert not str(call["cwd"]).startswith(str(tmp_path / "packet")), "an export, not the packet"
    cache = packet / "dependencies" / "dart" / "pub-cache"
    assert sorted(item.name for item in cache.iterdir()) == ["hosted", "hosted-hashes"]
    assert not (cache / "hosted" / "pub.dev" / ".cache").exists()
    assert DART.dart_packages(packet) == DART.DartDependencies(cache=cache.resolve(),
                                                               version="3.13.2")
    assert str(tmp_path) not in json.dumps(record)


def test_the_packet_s_cache_is_read_only_file_by_file_and_can_still_be_removed(
    tmp_path: Path, sdk: Any,
) -> None:
    """Claude's file tools run outside the command sandbox, so the files refuse a write too."""
    _record, packet, _pub = _fetch(tmp_path, {"pubspec.yaml": PUBSPEC, "pubspec.lock": LOCK})
    cache = packet / "dependencies" / "dart" / "pub-cache"
    for path in [cache, *cache.rglob("*")]:
        mode = path.lstat().st_mode & 0o777
        assert not mode & 0o222, (path, oct(mode))
    planted = cache / "hosted" / "pub.dev" / "inertdep-1.0.0" / "lib" / "inertdep.dart"
    with pytest.raises(PermissionError):
        planted.write_text("int two() => 3;\n", "utf-8")
    DART.unseal(packet / "dependencies" / "dart")
    shutil.rmtree(packet / "dependencies" / "dart")
    assert not (packet / "dependencies" / "dart").exists()


