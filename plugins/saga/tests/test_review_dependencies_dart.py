def test_two_fetches_of_one_head_write_the_same_bytes(tmp_path: Path, sdk: Any) -> None:
    pub = FakePub()
    first = _fetch(tmp_path / "1", {"pubspec.yaml": PUBSPEC, "pubspec.lock": LOCK}, pub)
    second = _fetch(tmp_path / "2", {"pubspec.yaml": PUBSPEC, "pubspec.lock": LOCK}, pub)
    assert pub.runs == 2
    assert first[0] == second[0]
    assert _contents(first[1]) == _contents(second[1])


