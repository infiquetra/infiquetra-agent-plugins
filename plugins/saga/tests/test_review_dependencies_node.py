class Result:
    def __init__(self, code: int, stdout: str = "", stderr: str = "") -> None:
        self.code, self.stdout, self.stderr = code, stdout, stderr


class FakeManager:
    """git answers ``ls-tree`` from *tree*; the watcher's command is the package manager, faked:
    it writes a ``node_modules`` as a real install would, with the state files and links each
    manager leaves, in a random order."""

    def __init__(self, tree: dict[str, str], *, result: Result | None = None,
                 timeout: bool = False, nothing: bool = False) -> None:
        self.tree, self.result, self.timeout, self.nothing = tree, result, timeout, nothing
        self.calls: list[dict[str, Any]] = []
        self.seen_files: list[str] = []

    def __call__(self, argv: list[str], *, cwd: Path, env: dict[str, str], timeout: int,
                 shell: bool, umask: int | None = None) -> Any:
        assert shell is False
        if argv[:2] == ["git", "ls-tree"]:
            lines = [f"{mode} blob {'0' * 40}\t{name}\n" for name, mode in self.tree.items()
                     if "-r" in argv or "/" not in name]
            return Result(0, "".join(lines))
        if argv[:2] == ["git", "cat-file"]:
            return Result(1)
        assert argv[:2] == [sys.executable, "-I"] and "--" in argv, argv
        command = argv[argv.index("--") + 1:]
        self.calls.append({"argv": command, "cwd": Path(cwd), "env": dict(env),
                           "watched": [argv[i + 1] for i, a in enumerate(argv) if a == "--watch"]})
        self.seen_files = sorted(
            str(path.relative_to(cwd)) for path in Path(cwd).rglob("*") if path.is_file())
        if self.timeout:
            raise subprocess.TimeoutExpired(command, timeout)
        if self.result is not None:
            return self.result
        if not self.nothing:
            _fake_install(Path(cwd))
        return Result(0)


def _fake_install(cwd: Path) -> None:
    modules = cwd / "node_modules"
    entries: list[tuple[str, Any]] = [
        ("left-pad/package.json", '{"name": "left-pad", "version": "1.3.0"}'),
        ("left-pad/index.js", "module.exports = (s) => s;\n"),
        ("@scope/tool/package.json", '{"name": "@scope/tool", "version": "2.0.0"}'),
        ("@scope/tool/cli.js", "#!/usr/bin/env node\n"),
        # State a manager keeps: a timestamp and the install's own absolute path.
        (".package-lock.json", f'{{"at": "{random.random()}"}}'),
        (".modules.yaml", f"prunedAt: {random.random()}\nstoreDir: {cwd}\n"),
        (".yarn-integrity", str(random.random())),
        (".pnpm-workspace-state-v1.json", str(random.random())),
        (".cache/tool/state", str(random.random())),
    ]
    random.shuffle(entries)
    for relative, text in entries:
        path = modules / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, "utf-8")
    (modules / "@scope" / "tool" / "cli.js").chmod(0o700)
    (modules / ".bin").mkdir()
    (modules / ".bin" / "tool").symlink_to("../@scope/tool/cli.js")
    # pnpm-style absolute link inside the folder, and a workspace link out of it.
    (modules / "pad-alias").symlink_to(modules / "left-pad")
    (cwd / "packages" / "sibling").mkdir(parents=True, exist_ok=True)
    (modules / "sibling").symlink_to("../packages/sibling")
    (modules / "outside").symlink_to("/etc")


def _export(files: dict[str, str]) -> Any:
    def export(folder: Path) -> bool:
        for name, text in files.items():
            path = folder / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, "utf-8")
        return True
    return export


def _fetch(tmp_path: Path, files: dict[str, str], runner: FakeManager | None = None,
           modes: dict[str, str] | None = None) -> tuple[dict[str, Any], Path, FakeManager]:
    tree = {name: (modes or {}).get(name, "100644") for name in files}
    runner = runner or FakeManager(tree)
    runner.tree = tree
    packet = tmp_path / "packet"
    packet.mkdir(parents=True, exist_ok=True)
    record = D.fetch(runner, tmp_path, "HEAD", packet, _export(files))
    (packet / D.FILE).write_text(json.dumps(record), "utf-8")
    return record, packet, runner


def _contents(folder: Path) -> dict[str, Any]:
    return {
        path.relative_to(folder).as_posix(): (
            ("link", os.readlink(path)) if path.is_symlink()
            else (path.stat().st_mode & 0o777, path.read_bytes()))
        for path in sorted(folder.rglob("*")) if path.is_symlink() or path.is_file()
    }


@pytest.fixture(autouse=True)
def _unseal_packets(tmp_path: Path) -> Any:
    """Installed trees are sealed read-only; give their folders write back so pytest can remove
    them, as whoever deletes a packet must."""
    yield
    for modules in tmp_path.rglob("node_modules"):
        if not modules.is_symlink():
            N.unseal(modules)


