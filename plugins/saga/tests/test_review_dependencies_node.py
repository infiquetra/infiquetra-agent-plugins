def test_the_rerun_helpers_link_and_find_node(tmp_path: Path) -> None:
    modules = tmp_path / "modules"
    modules.mkdir()
    copy = tmp_path / "copy"
    copy.mkdir()
    assert N.link_into(copy, modules) and (copy / "node_modules").resolve() == modules.resolve()
    assert not N.link_into(copy, modules)
    assert N.needs_node("npx") and N.needs_node("./node_modules/.bin/vitest")
    assert not N.needs_node("python3") and not N.needs_node("cargo")
