    (real / "node").write_text("#!/bin/sh\n", "utf-8")
    (real / "node").chmod(0o755)
    (tmp_path / "install" / "lib").mkdir()
    shims = tmp_path / "shims"
    shims.mkdir()
    (shims / "node").symlink_to(real / "node")
    assert N.node_bin(str(shims)) == real.resolve()
    assert N.node_bin(str(real)) is None
    assert N.toolchain_paths(str(shims)) == (real.resolve(), (tmp_path / "install" / "lib")
                                             .resolve())


