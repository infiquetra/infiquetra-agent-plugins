def cvss31_score(vector: object) -> float | None:
    """CVSS 3.x base score for a vector string, else None.

    Integer math per the FIRST 3.1 specification, so no float drift. Vectors
    that are not 3.0/3.1, that miss a base metric, or that name an unknown
    value do not score; temporal metrics are ignored. Unscorable means the
    advisory counts as no score, hence high.
    """
    if not isinstance(vector, str):
        return None
    parts = vector.split("/")
    if len(parts) < 2 or parts[0] not in ("CVSS:3.0", "CVSS:3.1"):
        return None
    metrics: dict[str, str] = {}
    for part in parts[1:]:
        name, separator, value = part.partition(":")
        if not separator or not name or not value:
            return None
        metrics[name] = value
    try:
        attack_vector = {"N": 0.85, "A": 0.62, "L": 0.55, "P": 0.2}[metrics["AV"]]
        attack_complexity = {"L": 0.77, "H": 0.44}[metrics["AC"]]
        scope_changed = {"U": False, "C": True}[metrics["S"]]
        if scope_changed:
            privileges = {"N": 0.85, "L": 0.68, "H": 0.5}[metrics["PR"]]
        else:
            privileges = {"N": 0.85, "L": 0.62, "H": 0.27}[metrics["PR"]]
        interaction = {"N": 0.85, "R": 0.62}[metrics["UI"]]
        impact_value = {"H": 0.56, "L": 0.22, "N": 0.0}
        confidentiality = impact_value[metrics["C"]]
        integrity = impact_value[metrics["I"]]
        availability = impact_value[metrics["A"]]
    except KeyError:
        return None
    impact_sub = 1.0 - (1.0 - confidentiality) * (1.0 - integrity) * (1.0 - availability)
    if scope_changed:
        impact = 7.52 * (impact_sub - 0.029) - 3.25 * (impact_sub - 0.02) ** 15
        exploitability = 8.22 * attack_vector * attack_complexity * privileges * interaction
        raw = min(1.08 * (impact + exploitability), 10.0)
    else:
        impact = 6.42 * impact_sub
        exploitability = 8.22 * attack_vector * attack_complexity * privileges * interaction
        raw = min(impact + exploitability, 10.0)
    if impact_sub <= 0.0:
        return 0.0
    # FIRST roundup: the smallest one-decimal number at or above the input.
    scaled = int(round(raw * 100000))
    if scaled % 10000 == 0:
        return scaled / 100000
    return (math.floor(scaled / 10000) + 1) / 10


def _document() -> dict[str, object]:
    loaded = yaml.safe_load(review_tools.TOOL_LIST.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise review_tools.RunnerFailure(2, "review-tools.yaml must be an object")
    return loaded


def _walk(root: Path) -> list[Path]:
    """Tracked files under ``root`` with caches and env trees pruned."""
    return review_tools.scan_files(root, _PRUNE_DIRS)


def _has_markers(root: Path) -> bool:
    for path in _walk(root):
        if path.name in _RUST_MARKER_NAMES:
            return True
    return False


def _files_with(root: Path, suffixes: tuple[str, ...]) -> list[str]:
    return sorted(
        path.relative_to(root).as_posix()
        for path in _walk(root)
        if path.suffix in suffixes
    )


def _base_file(context: ScanContext, name: str) -> Path | None:
    for staged_name, staged_path in context.base_files:
        if staged_name == name:
            return staged_path
    return None


def _stage_base(context: ScanContext, name: str, dest: str | None = None) -> Path | None:
    """Copy the staged base file over the stripped name in the scan tree."""
    staged = _base_file(context, name)
    if staged is None:
        return None
    target = context.root / (dest or name)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(staged.read_bytes())
    return target


def _stage_first_base(context: ScanContext, names: tuple[str, ...]) -> Path | None:
    for name in names:
        staged = _stage_base(context, name)
        if staged is not None:
            return staged
    return None


def _stage_toolchain(context: ScanContext) -> None:
    for name in _TOOLCHAIN_FILES:
        _stage_base(context, name)


def _invoke_cargo_deny(context: ScanContext) -> list[str]:
    if not _has_markers(context.root):
        return []
    if not (context.root / "Cargo.lock").is_file():
        return []
    staged = _stage_base(context, _DENY_CONFIG)
    if staged is None:
        staged = context.root / _DENY_CONFIG
        staged.write_text(_GENERATED_DENY_CONFIG, encoding="utf-8")
    return [
        "cargo-deny", "--format", "json", "--config", str(staged),
        "check", "advisories",
    ]


def _deny_advisory_ids(advisory: Mapping[str, object]) -> list[str]:
    found: list[str] = []
    ident = advisory.get("id")
    if isinstance(ident, str) and ident:
        found.append(ident)
    aliases = advisory.get("aliases") or []
    if isinstance(aliases, list):
        for alias in aliases:
            if isinstance(alias, str) and alias and alias not in found:
                found.append(alias)
    return found


def _parse_cargo_deny(text: str) -> ParseResult:
    hits: list[Hit] = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(entry, dict) or entry.get("type") != "diagnostic":
            continue
        fields = entry.get("fields")
        if not isinstance(fields, dict):
            continue
        if str(fields.get("severity") or "").lower() == "note":
            # Base-config ignores report at note severity; the base config is
            # trusted, so ignored advisories stay silent.
            continue
        code = str(fields.get("code") or "")
        advisory = fields.get("advisory")
        if code == "vulnerability":
            if not isinstance(advisory, dict):
                continue
            identifiers = _deny_advisory_ids(advisory)
            if not identifiers:
                continue
            score = cvss31_score(advisory.get("cvss"))
            package = str(advisory.get("package") or "unknown package")
            hits.append(Hit(
                rule_id=identifiers[0],
                path="Cargo.lock",
                statement=(
                    f"cargo-deny reports {identifiers[0]} in {package}."
                ),
                anchor=identifiers[0],
                advisory_ids=tuple(identifiers),
                score=score,
                row=review_formula.dependency_row(score),
                whole_project=True,
            ))
        elif code in _NON_VULNERABILITY_CODES:
            if isinstance(advisory, dict):
                identifiers = _deny_advisory_ids(advisory)
                if not identifiers:
                    continue
                rule_id = identifiers[0]
                package = str(advisory.get("package") or "unknown package")
                statement = f"cargo-deny reports {code} {rule_id} in {package}."
            else:
                match = _YANKED_PACKAGE.search(str(fields.get("message") or ""))
                package = match.group(1) if match else "unknown package"
                rule_id = f"yanked-{package}"
                identifiers = []
                statement = f"cargo-deny reports yanked {package}."
            hits.append(Hit(
                rule_id=rule_id,
                path="Cargo.lock",
                statement=statement,
                anchor=rule_id,
                advisory_ids=tuple(identifiers),
                row="security.dependency-medium-low",
                whole_project=True,
            ))
    return ParseResult(tuple(hits))


def _primary_span(message: Mapping[str, object]) -> Mapping[str, object] | None:
    spans = message.get("spans") or []
    if not isinstance(spans, list):
        return None
    for span in spans:
        if isinstance(span, dict) and span.get("is_primary"):
            return span
    for span in spans:
        if isinstance(span, dict):
            return span
    return None


def _compiler_messages(text: str) -> list[dict[str, object]]:
    """compiler-message payloads from a cargo JSON stream, in order."""
    found: list[dict[str, object]] = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(entry, dict) or entry.get("reason") != "compiler-message":
            continue
        message = entry.get("message")
        if isinstance(message, dict):
            found.append(message)
    return found


def _invoke_cargo_check(context: ScanContext) -> list[str]:
    if not _has_markers(context.root):
        return []
    if not _files_with(context.root, _RUST_SUFFIXES):
        return []
    _stage_toolchain(context)
    return ["cargo", "check", "--locked", "--message-format=json"]


def _stable_cargo_stream(text: str) -> str:
    """A cargo JSON stream with its records sorted.

    Each line is one independent record. A workspace build finishes its crates
    in a different order each run, so the stored stream must not keep that order.
    """
    lines = sorted(line.strip() for line in text.splitlines() if line.strip())
    return "".join(f"{line}\n" for line in lines)


def _parse_cargo_check(text: str) -> ParseResult:
    hits: list[Hit] = []
    for message in _compiler_messages(text):
        if str(message.get("level") or "") != "error":
            continue
        code = message.get("code")
        rule_id = code.get("code") if isinstance(code, dict) else None
        rule_id = str(rule_id) if rule_id else "rustc-error"
        span = _primary_span(message)
        path = str((span or {}).get("file_name") or ".")
        try:
            start = int((span or {}).get("line_start") or 0) or None
        except (TypeError, ValueError):
            start = None
        try:
            end = int((span or {}).get("line_end") or 0) or None
        except (TypeError, ValueError):
            end = None
        detail = str(message.get("message") or "").strip()
        hits.append(Hit(
            rule_id=rule_id,
            path=path,
            statement=f"rustc {rule_id}: {detail}.",
            anchor=f"{rule_id}: {detail}",
            start=start,
            end=end or start,
            row="correctness.type-error",
            whole_project=True,
        ))
    return ParseResult(tuple(hits))


def _invoke_clippy(context: ScanContext) -> list[str]:
    if not _has_markers(context.root):
        return []
    if not _files_with(context.root, _RUST_SUFFIXES):
        return []
    _stage_toolchain(context)
    _stage_first_base(context, _CLIPPY_CONFIGS)
    return [
        "cargo-clippy", "clippy", "--locked", "--message-format=json",
        "--", *_CLIPPY_LEVELS,
    ]


def _parse_clippy(text: str) -> ParseResult:
    hits: list[Hit] = []
    for message in _compiler_messages(text):
        level = str(message.get("level") or "")
        if level not in ("error", "warning"):
            continue
        code = message.get("code")
        name = code.get("code") if isinstance(code, dict) else None
        name = str(name) if name else ""
        if level == "error" and not name.startswith("clippy::"):
            # Rustc errors belong to cargo-check; without this split the same
            # error would arrive twice.
            continue
        rule_id = name or "rustc-warning"
        span = _primary_span(message)
        path = str((span or {}).get("file_name") or ".")
        try:
            start = int((span or {}).get("line_start") or 0) or None
        except (TypeError, ValueError):
            start = None
        try:
            end = int((span or {}).get("line_end") or 0) or None
        except (TypeError, ValueError):
            end = None
        detail = str(message.get("message") or "").strip()
        hits.append(Hit(
            rule_id=rule_id,
            path=path,
            statement=f"clippy {rule_id}: {detail}.",
            anchor=f"{rule_id}: {detail}",
            start=start,
            end=end or start,
            level="error" if level == "error" else "warning",
        ))
    return ParseResult(tuple(hits))


def _invoke_cargo_mutants(context: ScanContext) -> list[str]:
    if not _has_markers(context.root):
        return []
    if not _files_with(context.root, _RUST_SUFFIXES):
        return []
    if context.change is not None and not any(
        item.path.endswith(_RUST_SUFFIXES) and item.lines for item in context.change.files
    ):
        raise ToolGap("nothing-to-mutate", _MUTANT_ROW)
    _stage_toolchain(context)
    diff = _write_in_diff(context)
    # --workspace: without it cargo-mutants mutates only the package in the
    # current directory, so a change in any other workspace member is never tested.
    argv = [
        "cargo-mutants", "mutants", "-C", "--locked", "--workspace", "--in-diff", str(diff),
    ]
    if not _repository_sets_mutant_timeout(context.root):
        argv.extend(["--timeout", str(_MUTANT_TEST_TIMEOUT)])
    # nextest runs each test in its own process, which breaks suites whose tests
    # share temporary paths (issue 253 saw ripgrep's baseline fail). Use it only when
    # the repository configures it (issue 253); a ``test_tool`` in
    # .cargo/mutants.toml is read by cargo-mutants itself.
    nextest = context.root / _NEXTEST_CONFIG
    if nextest.is_file() and not nextest.is_symlink() and shutil.which("cargo-nextest"):
        argv.extend(["--test-tool", "nextest"])
    return argv


def _repository_sets_mutant_timeout(root: Path) -> bool:
    """True when .cargo/mutants.toml sets the timeout scaling itself (issue 260)."""
    config = root / _MUTANTS_CONFIG
    if not config.is_file() or config.is_symlink():
        return False
    try:
        settings = tomllib.loads(config.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, tomllib.TOMLDecodeError):
        return False
    return any(key in settings for key in _MUTANTS_OWN_TIMEOUT_KEYS)


def _write_in_diff(context: ScanContext) -> Path:
    """The change's diff, for ``--in-diff``, so only changed lines are mutated (issue 244).

    Without it cargo-mutants tests every mutant in the workspace and the review
    keeps only those on changed lines; on a real workspace that never finishes.
    """
    if not context.base or context.scratch is None:
        raise ToolGap("diff-unavailable", _MUTANT_ROW)
    result = subprocess.run(  # nosec B603 B607
        [
            "git", "diff", "--no-ext-diff", "--no-textconv", "--no-color", "--no-renames",
            context.base, "HEAD",
        ],
        cwd=context.root, capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise ToolGap("diff-unavailable", _MUTANT_ROW)
    target = context.scratch / _IN_DIFF
    # A retried run (issue 260) invokes this again in the same scratch folder. Unlinking first
    # keeps O_EXCL | O_NOFOLLOW meaningful: the file is always created fresh by this call.
    target.unlink(missing_ok=True)
    descriptor = os.open(
        target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600
    )
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(result.stdout)
    return target


def _without_times(value: object) -> object:
    if isinstance(value, dict):
        return {
            key: _without_times(item) for key, item in value.items() if key not in _MUTANT_TIMES
        }
    if isinstance(value, list):
        return [_without_times(item) for item in value]
    return value


def _stable_mutants(text: str) -> str:
    """outcomes.json without timings, outcomes sorted. Console text passes through."""
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return text
    data = _without_times(data)
    if isinstance(data, dict) and isinstance(data.get("outcomes"), list):
        data["outcomes"] = sorted(
            data["outcomes"], key=lambda item: json.dumps(item, sort_keys=True)
        )
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _parse_cargo_mutants(text: str) -> ParseResult:
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        if any(message in text for message in _NOTHING_TO_MUTATE):
            # A clean answer, not a failure: the changed lines hold no mutant.
            raise ToolGap("nothing-to-mutate", _MUTANT_ROW) from exc
        raise ValueError("cargo-mutants outcomes are not json") from exc
    if not isinstance(data, dict):
        raise ValueError("cargo-mutants outcomes must be an object")
    outcomes = data.get("outcomes") or []
    if not isinstance(outcomes, list):
        raise ValueError("cargo-mutants outcomes must be a list")
    hits: list[Hit] = []
    timed_out = False
    for outcome in outcomes:
        if not isinstance(outcome, dict):
            continue
        summary = str(outcome.get("summary") or "")
        if summary == "Timeout":
            timed_out = True
            continue
        if summary != "MissedMutant":
            continue
        scenario = outcome.get("scenario") or {}
        mutant = scenario.get("Mutant") if isinstance(scenario, dict) else None
        if not isinstance(mutant, dict):
            continue
        name = str(mutant.get("name") or "mutant")
        match = _MUTANT_NAME.match(name)
        anchor = match.group(2).strip() if match else name
        path = str(mutant.get("file") or ".")
        span = mutant.get("span") or {}
        begin = span.get("start") if isinstance(span, dict) else None
        finish = span.get("end") if isinstance(span, dict) else None
        try:
            start = int((begin or {}).get("line") or 0) or None
        except (TypeError, ValueError):
            start = None
        try:
            end = int((finish or {}).get("line") or 0) or None
        except (TypeError, ValueError):
            end = None
        hits.append(Hit(
            rule_id="surviving-mutant",
            path=path,
            statement=f"cargo-mutants mutant survived: {name}.",
            anchor=anchor,
            start=start,
            end=end or start,
            row="testing.surviving-mutant",
        ))
    # A timed-out mutant was neither caught nor missed, so the run cannot vouch for a
    # clean surviving-mutant row; survivors are still reported (issue 253).
    gaps = ((_MUTANT_TIMEOUT, _MUTANT_ROW),) if timed_out else ()
    return ParseResult(tuple(hits), gaps=gaps)


