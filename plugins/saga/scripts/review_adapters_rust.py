def _parse_cargo_machete(text: str) -> ParseResult:
    row = "architecture-maintainability.complexity-dead-code-naming"
    hits: list[Hit] = []
    manifest: str | None = None
    for line in text.splitlines():
        section = _MACHETE_SECTION.match(line)
        if section is not None:
            manifest = section.group(2).strip()
            continue
        name = line.strip()
        if manifest is None or not name or line[:1] not in (" ", "\t"):
            continue
        hits.append(Hit(
            rule_id="unused-dependency",
            path=manifest,
            statement=f"cargo-machete reports unused dependency {name}.",
            anchor=f"dependency {name}",
            row=row,
            whole_project=True,
        ))
    return ParseResult(tuple(hits))


