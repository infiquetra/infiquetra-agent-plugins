import os
import re
from collections.abc import Mapping
from pathlib import Path

import yaml

import review_formula
import review_tools
from review_tools import Adapter, Hit, ParseResult, RulePin, ScanContext, ToolGap

_DART_MARKER_NAMES = frozenset({
    "pubspec.yaml", "pubspec.lock",
})
_DART_SUFFIXES = (".dart",)
_PRUNE_DIRS = frozenset({".git", ".dart_tool"})
_ANALYSIS_OPTIONS = "analysis_options.yaml"
_PUBSPEC = "pubspec.yaml"
# The dependency keys whose presence means the tree needs package resolution.
_PUBSPEC_DEP_KEYS = ("dependencies", "dev_dependencies", "dependency_overrides")

